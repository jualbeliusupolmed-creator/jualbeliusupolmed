export async function syncMetaHtml({ check = false } = {}) {
  const markdown = await readFile(markdownPath, "utf8");
  const expected = await renderMetaHtml(markdown);
  let actual = "";
  try {
    actual = await readFile(htmlPath, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }

  if (actual === expected) return false;
  if (check) {
    console.error("docs/meta.html is out of sync. Run `npm run sync:meta-docs`.");
    return true;
  }

  await writeFile(htmlPath, expected);
  console.log("Generated docs/meta.html from docs/meta.md.");
  return true;
}

async function watchMetaMarkdown() {
  const { watch } = await import("node:fs");
  await syncMetaHtml();
  let timer;
  const watcher = watch(markdownPath, () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      syncMetaHtml().catch((error) => {
        console.error("Could not regenerate docs/meta.html:", error);
        process.exitCode = 1;
      });
    }, 120);
  });
  console.log("Watching docs/meta.md for changes. Press Ctrl+C to stop.");
  return watcher;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const mode = process.argv[2] || "sync";
  if (mode === "check") {
    if (await syncMetaHtml({ check: true })) process.exitCode = 1;
  } else if (mode === "watch") {
    await watchMetaMarkdown();
  } else if (mode === "sync") {
    await syncMetaHtml();
  } else {
    console.error(`Unknown mode "${mode}". Use sync, check, or watch.`);
    process.exitCode = 2;
  }
}
