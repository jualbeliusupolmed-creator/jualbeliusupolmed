import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { marked } from "marked";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const markdownPath = path.join(root, "docs/meta.md");
const htmlPath = path.join(root, "docs/meta.html");

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function plainHeading(value) {
  return value
    .replace(/!\[([^\]]*)\]\([^)]+\)/g, "$1")
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
    .replace(/[`*_~]/g, "")
    .trim();
}

function slugify(value) {
  return plainHeading(value)
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^\p{Letter}\p{Number} -]/gu, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "") || "bagian";
}

function safeHref(value, { image = false } = {}) {
  const href = String(value || "").trim();
  if (!href || /[\u0000-\u0020\u007f]/.test(href)) return null;
  if (/^[a-z][a-z\d+.-]*:/i.test(href)) {
    const protocol = href.match(/^([a-z][a-z\d+.-]*):/i)?.[1]?.toLowerCase();
    if (image ? protocol !== "https" : !["https", "http", "mailto"].includes(protocol)) return null;
  } else if (href.startsWith("//") || href.startsWith("\\\\")) {
    return null;
  }
  return href;
}

function getSections(markdown) {
  const slugs = new Map();
  return marked.lexer(markdown)
    .filter((token) => token.type === "heading" && token.depth === 2)
    .map((token) => {
      const title = plainHeading(token.text);
      const base = slugify(token.text);
      const count = slugs.get(base) || 0;
      slugs.set(base, count + 1);
      return { title, id: count ? `${base}-${count}` : base };
    });
}

function renderMarkdown(markdown) {
  const slugs = new Map();
  const renderer = new marked.Renderer();
  renderer.heading = function ({ tokens, depth }) {
    const body = this.parser.parseInline(tokens);
    if (depth !== 2) return `<h${depth}>${body}</h${depth}>\n`;

    const base = slugify(body.replace(/<[^>]*>/g, ""));
    const count = slugs.get(base) || 0;
    slugs.set(base, count + 1);
    const id = count ? `${base}-${count}` : base;
    return `<h2 id="${escapeHtml(id)}">${body}</h2>\n`;
  };
  renderer.link = function ({ href, title, tokens }) {
    const safe = safeHref(href);
    const body = this.parser.parseInline(tokens);
    if (!safe) return body;
    const titleAttribute = title ? ` title="${escapeHtml(title)}"` : "";
    const external = /^https?:/i.test(safe);
    const externalAttributes = external ? ' target="_blank" rel="noopener noreferrer"' : "";
    return `<a href="${escapeHtml(safe)}"${titleAttribute}${externalAttributes}>${body}</a>`;
  };
  renderer.image = function ({ href, title, text }) {
    const safe = safeHref(href, { image: true });
    if (!safe) return escapeHtml(text);
    const titleAttribute = title ? ` title="${escapeHtml(title)}"` : "";
    return `<img src="${escapeHtml(safe)}" alt="${escapeHtml(text)}"${titleAttribute}>`;
  };
  const renderTable = renderer.table;
  renderer.table = function (token) {
    return `<div class="table-wrap">${renderTable.call(this, token)}</div>\n`;
  };
  renderer.html = ({ text }) => escapeHtml(text);

  return marked.parse(markdown, {
    gfm: true,
    breaks: false,
    renderer,
  });
}

